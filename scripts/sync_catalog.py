#!/usr/bin/env python3
"""Generate or check user-facing catalog artifacts without changing skill methods."""
import argparse
import json
from pathlib import Path
import re

import yaml

START = '<!-- skills-catalog:start -->'
END = '<!-- skills-catalog:end -->'
ORIGINS = {'migrated': '既有技能迁入', 'distilled': '素材提炼', 'navigation': '导航入口'}
CALIBRATION = {'source-backed': '有作者来源，适配未全量校准', 'partial': '部分条件经本人确认', 'candidate': '候选，待本人校准', 'not-applicable': '导航职责'}
BEHAVIOR = {'structure-only': '结构检查', 'instruction-smoke': '有限指令冒烟', 'needs-retest': '本轮改动待行为重测'}
BEHAVIOR_EN = {'structure-only': 'Structure check', 'instruction-smoke': 'Limited instruction smoke check', 'needs-retest': 'Behavioral retest pending'}
REQUIRED = ['display_name', 'display_name_en', 'short_description', 'core_judgment', 'core_judgment_en', 'when_to_use', 'input_example', 'result_example', 'boundary', 'group', 'validation_report']


def cell(value: str) -> str:
    return value.replace('|', '\\|').replace('\n', ' ')


def render(root: Path) -> dict[str, str]:
    root = root.resolve()
    data = json.loads((root / 'catalog/skills.json').read_text())
    if not isinstance(data, dict) or not isinstance(data.get('skills'), list):
        raise ValueError('catalog skills must be a list')
    version = data.get('version')
    if not isinstance(version, str) or not re.fullmatch(r'\d+\.\d+\.\d+', version):
        raise ValueError('catalog version must be semantic x.y.z')
    names = set()
    entries = data['skills']
    for e in entries:
        if not isinstance(e, dict):
            raise ValueError('invalid catalog entry')
        name = e.get('name')
        if not isinstance(name, str) or not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', name) or len(name) > 64:
            raise ValueError('invalid skill name')
        if name in names:
            raise ValueError('duplicate skill name: ' + name)
        names.add(name)
        if e.get('path') != 'skills/' + name:
            raise ValueError('skill path must match name: ' + name)
        if e.get('invocation') not in ['explicit', 'automatic']:
            raise ValueError('invalid invocation: ' + name)
        for field in REQUIRED:
            if not isinstance(e.get(field), str) or not e[field].strip():
                raise ValueError(f'{name}: missing {field}')
        for field, labels in [('origin', ORIGINS), ('author_calibration', CALIBRATION), ('behavior_validation', BEHAVIOR)]:
            if not isinstance(e.get(field), str) or e[field] not in labels:
                raise ValueError(f'{name}: invalid {field}')
        report = Path(e['validation_report'])
        if report.is_absolute() or '..' in report.parts or report.parts[:1] != ('evals',):
            raise ValueError(f'{name}: report path must stay in evals')
        if not (root / report).is_file():
            raise ValueError(f'{name}: missing validation report')

    readme = (root / 'README.md').read_text()
    chinese_readme = (root / 'README.zh-CN.md').read_text()
    for filename, content in [('README.md', readme), ('README.zh-CN.md', chinese_readme)]:
        if content.count(START) != 1 or content.count(END) != 1 or content.index(END) < content.index(START):
            raise ValueError(f'{filename} requires one ordered catalog marker pair')
    outputs = {}
    rows_en = ['| Skill | Core judgment | Behavior check |', '| --- | --- | --- |']
    rows_zh = ['| 指令 / 技能 | 核心判断 | 行为验证 |', '| --- | --- | --- |']
    groups = list(dict.fromkeys(e['group'] for e in entries))
    for group in groups:
        for e in entries:
            if e['group'] == group:
                rows_en.append(f"| [/{e['name']}]({e['path']}/SKILL.md) · {cell(e['display_name_en'])} · [Usage guide](docs/skills/{e['name']}.md) | {cell(e['core_judgment_en'])} | {BEHAVIOR_EN[e['behavior_validation']]} |")
                rows_zh.append(f"| [/{e['name']}]({e['path']}/SKILL.md) · {cell(e['display_name'])} · [使用说明](docs/skills/{e['name']}.md) | {cell(e['core_judgment'])} | {BEHAVIOR[e['behavior_validation']]} |")
    for filename, content, rows in [('README.md', readme, rows_en), ('README.zh-CN.md', chinese_readme, rows_zh)]:
        a = content.index(START) + len(START)
        b = content.index(END)
        outputs[filename] = content[:a] + '\n\n' + '\n'.join(rows) + '\n\n' + content[b:]

    method_rows = ['# 方法地图', '', '由 catalog/skills.json 生成。表格用于导航；推荐前读取实际可用的技能入口。常用路径见 [任务路径](task-flows.md)。', '', '| 用户任务 | 方法 | 边界与关键判断 |', '| --- | --- | --- |']
    for e in entries:
        name = e['name']
        if name != 'ask-liyuk':
            method_rows.append(f"| {cell(e['when_to_use'])} | {name} | {cell(e['boundary'])} {cell(e['core_judgment'])} |")
        mode = '用户主动调用；不会自动启动。' if e['invocation'] == 'explicit' else '可以主动调用，也可由Agent按任务匹配使用。'
        outputs[f'docs/skills/{name}.md'] = f'''<!-- Generated by scripts/sync_catalog.py; edit catalog/skills.json. -->
# {e['display_name']}

## 用来做什么

{e['short_description']}。{e['core_judgment']}。

## 什么时候用

{e['when_to_use']}。{mode}

{e['boundary']}

## 输入与产物

示例输入：

> {e['input_example']}

预期产物：{e['result_example']} 这是使用示意，不是已运行结果。

Claude Code 文件安装后用 `/{name}`；Codex 用 `${name}`。Claude Code 插件安装时，命令需加实际插件名作为前缀。

## 判断是否有用

检查输出是否遵守这项关键判断：{e['core_judgment']}。如果只是套用格式、提出不影响决定的问题或没有依据的结论，记录输入与失误，再修正方法。

## 来源与验证状态

- 来源：{ORIGINS[e['origin']]}。
- 作者校准：{CALIBRATION[e['author_calibration']]}。
- 行为验证：{BEHAVIOR[e['behavior_validation']]}；范围见 [验证记录](../../{e['validation_report']})。

[技能正文](../../{e['path']}/SKILL.md)包含实际方法与按需参考。迁入、作者校准和行为验证是不同维度，均不单独证明普遍有效。
'''
        meta_path = root / e['path'] / 'agents/openai.yaml'
        meta = yaml.safe_load(meta_path.read_text()) if meta_path.is_file() else {}
        if not isinstance(meta, dict):
            raise ValueError(f'{name}: invalid client metadata')
        interface = meta.setdefault('interface', {})
        if not isinstance(interface, dict):
            raise ValueError(f'{name}: invalid client interface')
        interface.update(display_name=e['display_name'], short_description=e['short_description'])
        policy = meta.setdefault('policy', {})
        if not isinstance(policy, dict):
            raise ValueError(f'{name}: invalid client policy')
        if e['invocation'] == 'explicit':
            policy['allow_implicit_invocation'] = False
        elif 'allow_implicit_invocation' in policy:
            policy['allow_implicit_invocation'] = True
        if not policy:
            meta.pop('policy', None)
        outputs[e['path'] + '/agents/openai.yaml'] = yaml.safe_dump(meta, allow_unicode=True, sort_keys=False)
    if 'ask-liyuk' in names:
        outputs['skills/ask-liyuk/references/method-map.md'] = '\n'.join(method_rows) + '\n'
    plugin = json.loads((root / '.claude-plugin/plugin.json').read_text())
    if not isinstance(plugin, dict):
        raise ValueError('plugin must be an object')
    plugin.update(version=version, skills=['./' + e['path'] for e in entries])
    outputs['.claude-plugin/plugin.json'] = json.dumps(plugin, ensure_ascii=False, indent=2) + '\n'
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--write', action='store_true')
    args = parser.parse_args()
    try:
        outputs = render(args.root)
        drift = []
        for relative, text in outputs.items():
            path = args.root / relative
            if not path.is_file() or path.read_text() != text:
                drift.append(relative)
                if args.write:
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_text(text)
        if drift and args.check:
            print('Catalog drift: ' + ', '.join(drift))
            return 1
        print(('Updated' if args.write else 'Checked') + f' {len(outputs)} catalog artifacts.')
        return 0
    except (OSError, ValueError, yaml.YAMLError) as exc:
        print('ERROR:', exc)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
